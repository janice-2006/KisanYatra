def get_localized_disease_info(language_code, disease_key, disease_info):
    """Return a description/treatment/prevention dict localized to language_code.

    Falls back to the English disease_info (from DISEASE_REMEDIES) if the
    language is English, or if no translation exists yet for this disease_key.
    disease_info must be the original English dict for this class (with
    'description', 'treatment', 'prevention' keys) so the fallback always
    has something to show.
    """
    if not disease_info:
        return None
    if language_code == "en":
        return disease_info

    translated = DISEASE_DETAIL_TRANSLATIONS.get(disease_key, {}).get(language_code)
    if not translated:
        return disease_info

    return {
        "description": translated.get("description", disease_info.get("description", "")),
        "treatment": translated.get("treatment", disease_info.get("treatment", [])),
        "prevention": translated.get("prevention", disease_info.get("prevention", "")),
    }